// DATABREAKs Engine 026 - performance recording render demonstration.
//
// A 2-bar loop at 120 BPM (exactly 4 s) built entirely by the Engine 026
// recorder in Loop-record mode. Nothing is programmed into the Pattern:
//   loop 0  a "played" drum part (humanised timing and velocities, kick,
//           snare, closed/open hats in a choke group) is free-played and
//           recorded (pass 1);
//   loop 1  the drums play back FROM THE RECORDING; a mono bass line is
//           overdubbed (pass 2);
//   loop 2  an FM melody and poly chords are overdubbed (pass 3);
//   loop 3  everything plays back from the recording;
//   loop 4  Replace mode, drums only, punched over bar 2: a new hi-hat
//           figure replaces the old drums there (pass 4);
//   loop 5  plays the replaced version;
//   loop 6  the replace pass is undone (during bar 1);
//   loop 7  plays the restored original.
// The live input is generated by a deterministic "performer" (fixed
// pseudo-random timing offsets). From loop 1 on, every sound of an earlier
// loop's material comes from recorder-generated events.
//
// Rendered with block sizes 1, 64, 256, 1000 and 4096; all must be
// bit-identical (commands are issued at musically neutral moments, and live
// input carries absolute sample timestamps). The 256-frame render is
// written to databreaks_engine_026_demo.wav (48 kHz, 16-bit stereo) in the
// current directory. Do not commit it.
//
// Host software render, NOT a recording of FM-1 hardware, and not listened
// to as part of the automated checks. Self-checks (exit code 1 on failure):
// written, finite, peak in range, no master clipping, nothing dropped or
// undelivered, expected recording/undo state, identical for every block size.

#include "audio_pipeline.h"

#include <algorithm>
#include <cmath>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <fstream>
#include <vector>

using namespace databreaks;

namespace {

using Pipeline = AudioPipeline<16>;
using Buffer = std::vector<StereoFrame>;

constexpr std::int64_t kLoop = 192000;  // 2 bars at 120 BPM, 48 kHz
constexpr std::int64_t kBar = kLoop / 2;
constexpr std::int64_t kSixteenth = kBar / 16;  // 6000
constexpr std::size_t kTotal = 8 * static_cast<std::size_t>(kLoop);

struct Noise {
    std::uint32_t state;
    double next() {
        state = state * 1664525u + 1013904223u;
        return static_cast<double>(state >> 8) / 8388607.5 - 1.0;
    }
};

Buffer makeKick() {
    Buffer s(SAMPLE_RATE * 4 / 10);
    double phase = 0.0;
    for (std::size_t i = 0; i < s.size(); ++i) {
        const double t = static_cast<double>(i) / SAMPLE_RATE;
        phase += 2.0 * PI * (48.0 + 100.0 * std::exp(-t * 30.0)) / SAMPLE_RATE;
        const double v = 0.7 * std::sin(phase) * std::exp(-t * 7.5);
        s[i] = {v, v};
    }
    return s;
}

Buffer makeSnare() {
    Buffer s(SAMPLE_RATE / 4);
    Noise noise{0x26u};
    for (std::size_t i = 0; i < s.size(); ++i) {
        const double t = static_cast<double>(i) / SAMPLE_RATE;
        const double v = 0.25 * std::sin(2.0 * PI * 190.0 * t) * std::exp(-t * 22.0) +
                         0.25 * noise.next() * std::exp(-t * 16.0);
        s[i] = {v, v * 0.9};
    }
    return s;
}

Buffer makeHat(double seconds, double decay, std::uint32_t seed) {
    Buffer s(static_cast<std::size_t>(SAMPLE_RATE * seconds));
    Noise noise{seed};
    double previous = 0.0;
    for (std::size_t i = 0; i < s.size(); ++i) {
        const double t = static_cast<double>(i) / SAMPLE_RATE;
        const double white = noise.next();
        const double v = 0.12 * (white - previous) * std::exp(-t * decay);
        previous = white;
        s[i] = {v * 0.8, v};
    }
    return s;
}

Buffer makeShaker() {
    Buffer s(SAMPLE_RATE / 12);
    Noise noise{0x5Au};
    for (std::size_t i = 0; i < s.size(); ++i) {
        const double t = static_cast<double>(i) / SAMPLE_RATE;
        const double env = std::sin(PI * std::min(1.0, t * 12.0)) * std::exp(-t * 20.0);
        const double v = 0.1 * noise.next() * env;
        s[i] = {v, v * 0.6};
    }
    return s;
}

enum Pad : int { Kick = 0, Snare = 4, ClosedHat = 13, OpenHat = 14, Shaker = 22 };

void program(Pipeline& p) {
    static const Buffer kick = makeKick();
    static const Buffer snare = makeSnare();
    static const Buffer closedHat = makeHat(0.06, 65.0, 0xC0DEu);
    static const Buffer openHat = makeHat(0.5, 6.0, 0xFACEu);
    static const Buffer shaker = makeShaker();
    p.drums().assignSample(Kick, &kick);
    p.drums().assignSample(Snare, &snare);
    p.drums().assignSample(ClosedHat, &closedHat);
    p.drums().assignSample(OpenHat, &openHat);
    p.drums().assignSample(Shaker, &shaker);
    p.drums().setChokeGroup(ClosedHat, 1);
    p.drums().setChokeGroup(OpenHat, 1);

    MonoParameters bass;
    bass.filterCutoff = 260.0;
    bass.filterEnvelopeAmount = 1500.0;
    bass.volume = 0.55;
    bass.envelope = {0.004, 0.2, 0.55, 0.06};
    p.mono().setParameters(bass);
    FMParameters bell;
    bell.modulationRatio = 2.0;
    bell.modulationDepth = 1.6;
    bell.volume = 0.24;
    bell.envelope = {0.004, 0.3, 0.3, 0.4};
    p.fm().setParameters(bell);
    PolyParameters pad;
    pad.detune = 0.005;
    pad.voiceVolume = 0.08;
    pad.stereoWidth = 0.8;
    pad.envelope = {0.25, 0.5, 0.7, 0.8};
    p.poly().setParameters(pad);

    p.setDrumLevel(0.7);
    p.setMonoLevel(0.75);
    p.setFmLevel(0.7);
    p.setPolyLevel(0.8);
    p.setMasterLevel(0.7);

    p.eq().setLow(90.0, 1.5);
    p.compressor().setThresholdDb(-20.0);
    p.compressor().setRatio(2.5);
    p.reverb().setDecaySeconds(1.6);
    p.reverb().setWetLevel(0.2);
    for (AudioEffect* e : {static_cast<AudioEffect*>(&p.eq()),
                           static_cast<AudioEffect*>(&p.compressor()),
                           static_cast<AudioEffect*>(&p.reverb())}) {
        e->setBypassed(false, true);
    }

    Sequencer& s = p.sequencer();
    s.clock().setTempo(120.0);
    s.pattern().configure({4, 4}, 2, 240);  // empty pattern: 2-bar loop
    s.recorder().setRecordMode(RecordMode::Loop);
    s.recorder().setWriteMode(WriteMode::Overdub);
}

// ---- The deterministic "performer" ------------------------------------------

struct Performer {
    std::vector<LiveEvent> events;
    Noise humanise{0x1234u};

    std::int64_t jitter(int amount) {
        return static_cast<std::int64_t>(std::lround(humanise.next() * amount));
    }
    void hitAt(int pad, std::int64_t t, int velocity) {
        events.push_back({LiveEventType::DrumHit, SynthTarget::Mono, pad,
                          std::clamp(velocity, 1, 127), std::max<std::int64_t>(0, t)});
    }
    void note(SynthTarget target, int n, std::int64_t t, std::int64_t length, int velocity) {
        events.push_back({LiveEventType::NoteOn, target, n, velocity, t});
        events.push_back({LiveEventType::NoteOff, target, n, 0, t + length});
    }
};

std::vector<LiveEvent> performance() {
    Performer p;
    // Loop 0: drums, two bars, played (not quantised).
    for (int bar = 0; bar < 2; ++bar) {
        const std::int64_t b = bar * kBar;
        for (int k : {0, 6, 10}) {
            p.hitAt(Kick, b + k * kSixteenth + p.jitter(150), 112 + static_cast<int>(p.jitter(10)));
        }
        if (bar == 1) p.hitAt(Kick, b + 15 * kSixteenth + p.jitter(120), 92);
        for (int k : {4, 12}) {
            p.hitAt(Snare, b + k * kSixteenth + 180 + p.jitter(120), 110 + static_cast<int>(p.jitter(8)));
        }
        for (int k = 0; k < 16; k += 2) {
            const int pad = (bar == 1 && k == 14) ? OpenHat : ClosedHat;
            p.hitAt(pad, b + k * kSixteenth + p.jitter(200),
                    (k % 4 == 0 ? 92 : 64) + static_cast<int>(p.jitter(12)));
        }
    }
    // Loop 1: bass overdub.
    const std::int64_t l1 = kLoop;
    const int bassNotes[2][4] = {{36, 36, 43, 41}, {33, 33, 40, 43}};
    for (int bar = 0; bar < 2; ++bar) {
        const int steps[4] = {0, 3, 8, 11};
        for (int i = 0; i < 4; ++i) {
            const std::int64_t t = l1 + bar * kBar + steps[i] * kSixteenth + p.jitter(250) + 250;
            p.note(SynthTarget::Mono, bassNotes[bar][i], t, (i == 1 ? 2 : 4) * kSixteenth - 900,
                   100 + static_cast<int>(p.jitter(15)));
        }
    }
    // Loop 2: FM melody and poly chords (one chord per bar).
    const std::int64_t l2 = 2 * kLoop;
    const int melody[][3] = {{0, 72, 3}, {3, 74, 3}, {6, 76, 2}, {8, 79, 6},
                             {16, 77, 3}, {19, 76, 3}, {22, 74, 2}, {24, 72, 8}};
    for (const auto& m : melody) {
        p.note(SynthTarget::Fm, m[1], l2 + m[0] * kSixteenth + p.jitter(300) + 300,
               m[2] * kSixteenth - 1500, 96 + static_cast<int>(p.jitter(14)));
    }
    const int chords[2][3] = {{48, 52, 55}, {45, 48, 52}};
    for (int bar = 0; bar < 2; ++bar) {
        for (int k = 0; k < 3; ++k) {
            p.note(SynthTarget::Poly, chords[bar][k], l2 + bar * kBar + k * 90,
                   kBar - 7000, 72);
        }
    }
    // Loop 4, bar 2: replacement drum figure (shaker + busier closed hats).
    const std::int64_t l4b2 = 4 * kLoop + kBar;
    for (int k = 0; k < 16; ++k) {
        p.hitAt(ClosedHat, l4b2 + k * kSixteenth + p.jitter(150), (k % 2 == 0 ? 84 : 52));
        if (k % 4 == 2) p.hitAt(Shaker, l4b2 + k * kSixteenth + 1500 + p.jitter(200), 90);
    }
    p.hitAt(Kick, l4b2 + p.jitter(100), 118);
    std::stable_sort(p.events.begin(), p.events.end(),
                     [](const LiveEvent& a, const LiveEvent& b) {
                         return a.sampleTime < b.sampleTime;
                     });
    return p.events;
}

struct Result {
    Buffer audio;
    std::uint64_t delivered = 0;
    std::uint64_t dropped = 0;
    std::uint64_t undelivered = 0;
    std::uint64_t clipped = 0;
    std::size_t recorded = 0;
    std::size_t visibleBeforeReplace = 0;
    std::size_t visibleAfterReplace = 0;
    std::size_t visibleAfterUndo = 0;
    std::size_t passes = 0;
    std::uint64_t late = 0;
    std::uint64_t overflow = 0;
};

Result renderWith(std::size_t block) {
    static Pipeline p;
    Sequencer& s = p.sequencer();
    s.stop();
    s.disarm();
    Buffer flush(1);
    p.render(flush.data(), 1);
    s.clearRecording();
    s.recorder().clearPunch();
    s.recorder().setTargets(RecordAll);
    p.drums().stopAll();
    p.mono().reset();
    p.fm().reset();
    p.poly().reset();
    p.effects().resetAll();
    s.pattern().clear();
    s.clock().reset();
    p.resetDiagnostics();
    program(p);
    p.effects().resetAll();
    const std::uint64_t d0 = s.deliveredEventCount();
    const std::uint64_t x0 = s.droppedEventCount();
    const std::uint64_t u0 = p.undeliveredSequencerEventCount();
    const std::uint64_t late0 = s.recorder().lateLiveCount();

    static const std::vector<LiveEvent> live = performance();
    Result r;
    r.audio.assign(kTotal, StereoFrame{});
    s.arm();
    s.start();
    std::size_t li = 0;
    bool replaceSet = false;
    bool undone = false;
    for (std::size_t pos = 0; pos < kTotal; pos += block) {
        const std::size_t n = std::min(block, kTotal - pos);
        const std::int64_t at = static_cast<std::int64_t>(pos);
        // Musically neutral command moments: anywhere in these windows gives
        // the same result (no input or affected event nearby).
        if (!replaceSet && at >= 3 * kLoop + kBar) {  // loop 3, bar 2
            r.visibleBeforeReplace = s.recorder().track().visibleCount();
            s.recorder().setWriteMode(WriteMode::Replace);
            s.recorder().setTargets(RecordDrums);
            s.recorder().setPunch(4 * 7680 + 3840, 5 * 7680);  // loop 4, bar 2
            replaceSet = true;
        }
        if (!undone && at >= 6 * kLoop + kBar / 4) {  // loop 6, bar 1
            r.visibleAfterReplace = s.recorder().track().visibleCount();
            s.disarm();
            s.undo();
            r.visibleAfterUndo = s.recorder().track().visibleCount();
            undone = true;
        }
        while (li < live.size() && live[li].sampleTime < at + static_cast<std::int64_t>(n)) {
            s.liveEvent(live[li++]);
        }
        p.render(r.audio.data() + pos, n);
    }
    r.delivered = s.deliveredEventCount() - d0;
    r.dropped = s.droppedEventCount() - x0;
    r.undelivered = p.undeliveredSequencerEventCount() - u0;
    r.clipped = p.clippedSampleCount();
    r.recorded = s.recorder().track().size();
    r.passes = s.recorder().track().undoablePassCount();
    r.late = s.recorder().lateLiveCount() - late0;
    r.overflow = s.recorder().track().passFullCount() + s.recorder().track().trackFullCount() +
                 s.recorder().heldFullCount() + s.recorder().pendingFullCount();
    return r;
}

void write16(std::ofstream& f, std::uint16_t v) {
    f.put(static_cast<char>(v & 0xFF));
    f.put(static_cast<char>((v >> 8) & 0xFF));
}

void write32(std::ofstream& f, std::uint32_t v) {
    write16(f, static_cast<std::uint16_t>(v & 0xFFFF));
    write16(f, static_cast<std::uint16_t>((v >> 16) & 0xFFFF));
}

bool writeWav(const char* path, const Buffer& audio) {
    std::ofstream f(path, std::ios::binary);
    if (!f) return false;
    const std::uint32_t dataSize = static_cast<std::uint32_t>(audio.size() * 4);
    f.write("RIFF", 4);
    write32(f, 36 + dataSize);
    f.write("WAVE", 4);
    f.write("fmt ", 4);
    write32(f, 16);
    write16(f, 1);
    write16(f, 2);
    write32(f, SAMPLE_RATE);
    write32(f, SAMPLE_RATE * 4);
    write16(f, 4);
    write16(f, 16);
    f.write("data", 4);
    write32(f, dataSize);
    for (const auto& frame : audio) {
        const auto l = static_cast<std::int16_t>(std::lround(clampAudio(frame.left) * 32767.0));
        const auto r = static_cast<std::int16_t>(std::lround(clampAudio(frame.right) * 32767.0));
        write16(f, static_cast<std::uint16_t>(l));
        write16(f, static_cast<std::uint16_t>(r));
    }
    return static_cast<bool>(f);
}

}  // namespace

int main() {
    std::printf("DATABREAKs Engine 026 - performance recording render demo\n");
    std::printf("Host software render; not an FM-1 hardware recording.\n");

    const Result reference = renderWith(256);
    bool identical = true;
    for (std::size_t block : {1u, 64u, 1000u, 4096u, 256u}) {
        const Result other = renderWith(block);
        bool same = other.delivered == reference.delivered &&
                    other.recorded == reference.recorded &&
                    other.visibleAfterUndo == reference.visibleAfterUndo;
        for (std::size_t i = 0; i < kTotal && same; ++i) {
            same = other.audio[i].left == reference.audio[i].left &&
                   other.audio[i].right == reference.audio[i].right;
        }
        std::printf("Block %4zu: %s\n", block, same ? "bit-identical" : "DIFFERENT");
        identical = identical && same;
    }

    double peak = 0.0;
    double energyL = 0.0;
    double energyR = 0.0;
    bool finite = true;
    for (const auto& f : reference.audio) {
        finite = finite && std::isfinite(f.left) && std::isfinite(f.right);
        peak = std::max(peak, std::max(std::abs(f.left), std::abs(f.right)));
        energyL += f.left * f.left;
        energyR += f.right * f.right;
    }

    const char* path = "databreaks_engine_026_demo.wav";
    const bool written = writeWav(path, reference.audio);

    std::printf("Frames: %zu (%.2f s), 120 BPM, 2-bar loop x 8, empty pattern\n", kTotal,
                static_cast<double>(kTotal) / SAMPLE_RATE);
    std::printf("Recorded events %zu; visible before replace %zu, after replace %zu, "
                "after undo %zu; undoable passes at end %zu\n",
                reference.recorded, reference.visibleBeforeReplace,
                reference.visibleAfterReplace, reference.visibleAfterUndo, reference.passes);
    std::printf("Sequencer events delivered %llu, dropped %llu, undelivered %llu, late %llu, "
                "recorder overflow %llu\n",
                static_cast<unsigned long long>(reference.delivered),
                static_cast<unsigned long long>(reference.dropped),
                static_cast<unsigned long long>(reference.undelivered),
                static_cast<unsigned long long>(reference.late),
                static_cast<unsigned long long>(reference.overflow));
    std::printf("Peak %.4f, master clipped samples %llu, RMS L/R %.4f / %.4f\n", peak,
                static_cast<unsigned long long>(reference.clipped),
                std::sqrt(energyL / kTotal), std::sqrt(energyR / kTotal));
    std::printf("Wrote %s: %s\n", path, written ? "ok" : "FAILED");

    const bool state = reference.visibleAfterReplace != reference.visibleBeforeReplace &&
                       reference.visibleAfterUndo == reference.visibleBeforeReplace &&
                       reference.passes == 3 && reference.visibleBeforeReplace == 49;
    const bool ok = written && finite && peak > 0.1 && peak < 1.0 && reference.clipped == 0 &&
                    reference.delivered > 400 && reference.dropped == 0 &&
                    reference.undelivered == 0 && reference.late == 0 &&
                    reference.overflow == 0 && state && identical && energyL > 0.0 &&
                    energyR > 0.0;
    std::printf(ok ? "ENGINE 026 RENDER PASSED\n" : "ENGINE 026 RENDER FAILED\n");
    return ok ? 0 : 1;
}
